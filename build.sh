#!/usr/bin/env bash
# Build system for the plant monitor: ESP32 firmware (PlatformIO) and the
# Rust server. Run `./build.sh help` for usage.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FW_DIR="$ROOT/firmware"
SERVER_DIR="$ROOT/server"
VENV="$ROOT/.tools/venv"

ENV_NAME="${PIO_ENV:-esp32dev}"
PORT="${PIO_PORT:-}"
PIO=""

usage() {
  cat <<EOF
Usage: $(basename "$0") <command> [options]

Firmware commands:
  setup          Install PlatformIO (into .tools/venv) and firmware libraries
  build          Compile the firmware
  flash          Compile and upload the firmware to a connected ESP32
  monitor        Open the serial monitor
  deploy         flash + monitor
  clean          Remove firmware build output

Server commands:
  server         Build the server (release) -> server/target/release/plant-server
  run-server     Build and run the server with server/config.toml
  test-server    Run the server's unit tests
  user-add NAME  Create a web UI login (uses server/config.toml)

Options:
  -p, --port <dev>   Serial port, e.g. /dev/ttyUSB0 (default: auto-detect)
  -e, --env <name>   PlatformIO environment from platformio.ini (default: $ENV_NAME)
  -h, --help         Show this help

Environment variables PIO_PORT and PIO_ENV work as defaults for the options.
EOF
}

log()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

# ------------------------------------------------------------------ helpers

ensure_pio() {
  if [[ -x "$VENV/bin/pio" ]]; then
    PIO="$VENV/bin/pio"
  elif command -v pio >/dev/null 2>&1; then
    PIO="$(command -v pio)"
  else
    command -v python3 >/dev/null 2>&1 || die "python3 is required to install PlatformIO"
    log "Installing PlatformIO into $VENV"
    python3 -m venv "$VENV"
    "$VENV/bin/pip" install --quiet --upgrade pip platformio
    PIO="$VENV/bin/pio"
  fi
}

ensure_secrets() {
  local secrets="$FW_DIR/include/secrets.h"
  if [[ ! -f "$secrets" ]]; then
    cp "$FW_DIR/include/secrets.h.example" "$secrets"
    die "Created firmware/include/secrets.h from the template. Edit it (WiFi, server URL, device key), then re-run."
  fi
  if grep -q 'CHANGE-ME' "$secrets"; then
    die "firmware/include/secrets.h still contains CHANGE-ME placeholders"
  fi
  generate_root_ca
}

# Embeds firmware/root_ca.pem (the CA that signed the server's HTTPS
# certificate) into the firmware as include/root_ca.h.
generate_root_ca() {
  local pem="$FW_DIR/root_ca.pem" header="$FW_DIR/include/root_ca.h"
  {
    echo "// Generated by build.sh from firmware/root_ca.pem. Do not edit."
    echo "#pragma once"
    if [[ -f "$pem" ]]; then
      grep -q "BEGIN CERTIFICATE" "$pem" || die "firmware/root_ca.pem is not a PEM certificate"
      echo 'static const char ROOT_CA[] = R"PEM('
      cat "$pem"
      echo ')PEM";'
    else
      echo 'static const char ROOT_CA[] = "";'
    fi
  } > "$header.tmp"
  mv "$header.tmp" "$header"
  if [[ -f "$pem" ]]; then
    log "Embedding root CA from firmware/root_ca.pem"
  elif grep -q '"https://' "$FW_DIR/include/secrets.h"; then
    die "SERVER_URL is https but firmware/root_ca.pem is missing (see README, 'HTTPS for the sensors')"
  fi
}

check_serial_access() {
  if ! id -nG | tr ' ' '\n' | grep -qxE 'dialout|uucp'; then
    warn "you are not in the 'dialout' group; uploading may fail with 'permission denied'."
    warn "fix: sudo usermod -aG dialout \$USER  (then log out and back in)"
  fi
}

pio_run() {
  "$PIO" run --project-dir "$FW_DIR" --environment "$ENV_NAME" "$@"
}

# ------------------------------------------------------------------ commands

cmd_setup() {
  ensure_pio
  log "Installing firmware dependencies"
  "$PIO" pkg install --project-dir "$FW_DIR" --environment "$ENV_NAME"
  log "PlatformIO ready: $PIO"
}

cmd_build() {
  ensure_pio
  ensure_secrets
  log "Building firmware ($ENV_NAME)"
  pio_run
}

cmd_flash() {
  ensure_pio
  ensure_secrets
  check_serial_access
  local args=(--target upload)
  [[ -n "$PORT" ]] && args+=(--upload-port "$PORT")
  log "Building and flashing firmware ($ENV_NAME)${PORT:+ to $PORT}"
  pio_run "${args[@]}"
}

cmd_monitor() {
  ensure_pio
  local args=(--project-dir "$FW_DIR" --environment "$ENV_NAME")
  [[ -n "$PORT" ]] && args+=(--port "$PORT")
  log "Serial monitor (Ctrl+C to quit). The node deep-sleeps between readings; press EN/RST to wake it."
  "$PIO" device monitor "${args[@]}"
}

cmd_clean() {
  ensure_pio
  pio_run --target clean
  rm -rf "$FW_DIR/.pio/build"
}

cmd_server() {
  command -v cargo >/dev/null 2>&1 || die "cargo not found; install Rust from https://rustup.rs"
  log "Building server (release)"
  cargo build --release --manifest-path "$SERVER_DIR/Cargo.toml"
  log "Binary: server/target/release/plant-server"
}

cmd_run_server() {
  local config="$SERVER_DIR/config.toml"
  if [[ ! -f "$config" ]]; then
    cp "$SERVER_DIR/config.example.toml" "$config"
    warn "created server/config.toml from the example; edit your plants there"
  fi
  cmd_server
  log "Starting server"
  cd "$SERVER_DIR"
  exec ./target/release/plant-server config.toml
}

cmd_user_add() {
  [[ -n "${ARG:-}" ]] || die "usage: $(basename "$0") user-add NAME"
  cmd_server
  cd "$SERVER_DIR"
  ./target/release/plant-server -c config.toml user-add "$ARG"
}

cmd_test_server() {
  cargo test --manifest-path "$SERVER_DIR/Cargo.toml"
}

# ------------------------------------------------------------------ main

COMMAND=""
ARG=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    -p|--port) [[ $# -ge 2 ]] || die "$1 needs a value"; PORT="$2"; shift 2 ;;
    -e|--env)  [[ $# -ge 2 ]] || die "$1 needs a value"; ENV_NAME="$2"; shift 2 ;;
    -h|--help|help) usage; exit 0 ;;
    -*) die "unknown option: $1 (see --help)" ;;
    *)
      if [[ -z "$COMMAND" ]]; then COMMAND="$1"
      elif [[ -z "$ARG" ]]; then ARG="$1"
      else die "too many arguments: $1"; fi
      shift ;;
  esac
done

case "${COMMAND:-}" in
  setup)       cmd_setup ;;
  build)       cmd_build ;;
  flash)       cmd_flash ;;
  monitor)     cmd_monitor ;;
  deploy)      cmd_flash; cmd_monitor ;;
  clean)       cmd_clean ;;
  server)      cmd_server ;;
  run-server)  cmd_run_server ;;
  test-server) cmd_test_server ;;
  user-add)    cmd_user_add ;;
  "")          usage; exit 1 ;;
  *)           die "unknown command: $COMMAND (see --help)" ;;
esac
